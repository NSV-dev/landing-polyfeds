const menuButton = document.querySelector(".menu-button");
const nav = document.querySelector(".nav");
const BREAKPOINTS = {
  mobileMax: 760,
  carouselMax: 1199,
  desktopMin: 1200,
  wideDesktopMin: 1440
};

function setMenuOpen(isOpen) {
  nav.classList.toggle("is-open", isOpen);
  menuButton.setAttribute("aria-expanded", String(isOpen));
  document.body.classList.toggle("menu-open", isOpen);
}

function detectInitialLanguage() {
  const saved = localStorage.getItem("language");
  if (saved === "ru" || saved === "en") return saved;

  const browserLangs = navigator.languages?.length ? navigator.languages : [navigator.language];
  const isRussianLocale = browserLangs.some((lang) => /^ru\b/i.test(lang));
  return isRussianLocale ? "ru" : "en";
}

function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  localStorage.setItem("language", lang);
  currentLang.textContent = lang.toUpperCase();

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = dictionary[node.dataset.i18n] || "";
  });

  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    node.innerHTML = dictionary[node.dataset.i18nHtml] || "";
  });

  normalizeDesktopProjectTitles(lang);
  normalizeDesktopExperienceText(lang);
  normalizeExperienceDurations(lang);
  document.dispatchEvent(new CustomEvent("languagechange"));
}

